# dict == ignores insertion order (also nested and inside lists / tuples)
def b(x):
    if x:
        print(1)
    else:
        print(0)
b({1: 2, 3: 4} == {3: 4, 1: 2})
b({1: 2, 3: 4} != {3: 4, 1: 2})
b({1: 2, 3: 4} == {3: 4, 1: 5})
b({1: 2, 3: 4} == {3: 4})
b({} == {})
b({"a": 1, "b": 2, "c": 3} == {"c": 3, "a": 1, "b": 2})
b({"a": 1, "b": 2} == {"a": 1, "c": 2})
b({"a": {1: 1, 2: 2}} == {"a": {2: 2, 1: 1}})
b([{1: 1, 2: 2}] == [{2: 2, 1: 1}])
b(({1: 1, 2: 2}, 5) == ({2: 2, 1: 1}, 5))
b({(1, 2): 3, (0, 5): 4} == {(0, 5): 4, (1, 2): 3})
b({1: 1, "a": 2, (3, 4): 5} == {(3, 4): 5, "a": 2, 1: 1})
b({-1: 1, 5: 2, 0: 3} == {0: 3, -1: 1, 5: 2})
b({1: [1, 2]} == {1: [1, 2]})
b({1: [1, 2]} == {1: [2, 1]})
d = {1: 1}
d[2] = 2
d[0] = 0
b(d == {0: 0, 1: 1, 2: 2})
e = {2: 2, 0: 0}
e[1] = 1
b(d == e)
b(d == [1, 2])
b(d == 3)
b({"b": 1, "a": 2} == {"a": 2, "b": 1})
b({"ab": 1, "b": 2} == {"b": 2, "ab": 1})
b({"": 1, "a": 2} == {"a": 2, "": 1})
b({1: 1, 2: 2, 3: 3, 4: 4} == {4: 4, 3: 3, 2: 2, 1: 1})
